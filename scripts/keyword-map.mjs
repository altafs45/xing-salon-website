// Writes docs/seo/seo-keyword-map.md from the built site: one row per indexable page. Run after a build.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const SITE = 'https://www.xingsalons.com';
const decode = (text) => text.replace(/&amp;/g, '&').replace(/&#x27;|&#39;/g, "'").replace(/&quot;/g, '"');
const paths = [...(readFileSync('dist/sitemap-pages.xml', 'utf8') + readFileSync('dist/sitemap-blog.xml', 'utf8')).matchAll(/<loc>([^<]+)<\/loc>/g)].map((m) => m[1].replace(SITE, '') || '/');
const html = new Map(paths.map((path) => [path, readFileSync(path === '/' ? 'dist/index.html' : join('dist', `${path}.html`), 'utf8')]));
const incoming = new Map(paths.map((path) => [path, 0]));
for (const page of html.values()) for (const path of new Set([...page.matchAll(/href="(\/[^"#?]*)/g)].map((m) => m[1]))) if (incoming.has(path)) incoming.set(path, incoming.get(path) + 1);

const rows = paths.map((path) => {
  const page = html.get(path);
  const title = decode(page.match(/<title>([^<]*)/)?.[1] ?? '');
  const description = decode(page.match(/name="description" content="([^"]*)/)?.[1] ?? '');
  const h1 = decode((page.match(/<h1[\s\S]*?<\/h1>/i)?.[0] ?? '').replace(/<[^>]+>/g, ' ')).replace(/\s+/g, ' ').trim();
  const primary = title.split(/ \| | – /)[0];
  return `| \`${path}\` | ${primary} | ${h1} | ${title} | ${description.length} chars | ${incoming.get(path)} |`;
});
writeFileSync('docs/seo/seo-keyword-map.md', ['# Keyword map', '', 'One primary keyword per page, generated by `node scripts/keyword-map.mjs`.', '', '`/services/global-hair-color` owns "hair colour in Bangalore". `/offers/november` owns "hair colour offer Bangalore". Blog posts own question keywords. Salon pages own "salon in <area>".', '', '| Page | Primary keyword | H1 | Title | Description | Pages linking in |', '| --- | --- | --- | --- | --- | --- |', ...rows, ''].join('\n'));
console.log(`${rows.length} pages mapped.`);
